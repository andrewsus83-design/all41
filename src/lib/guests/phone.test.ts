import { describe, expect, it } from "vitest";
import { normalizePhone } from "./phone";

describe("normalizePhone", () => {
  it.each([
    ["+6281234567890", "+6281234567890"],
    ["0812-3456-7890", "+6281234567890"],
    ["0812 3456 7890", "+6281234567890"],
    ["+62 812 3456 7890", "+6281234567890"],
    ["62 812 3456 7890", "+6281234567890"],
    ["6281234567890", "+6281234567890"],
    ["812 3456 7890", "+6281234567890"],
    ["+62 (0)812 3456 7890", "+6281234567890"],
    ["(021) 555-1234", "+62215551234"],
    ["+65 9123 4567", "+6591234567"],
    ["0065 9123 4567", "+6591234567"],
    ["+1 (415) 555-0132", "+14155550132"],
    ["  +6281234567890  ", "+6281234567890"],
  ])("reads %j as %s", (raw, expected) => {
    expect(normalizePhone(raw)).toBe(expected);
  });

  it.each(["", "   ", "abc", "12345", "+1", "+0123456789", "9123 4567", "+62812345678901234567"])(
    "refuses %j",
    (raw) => {
      expect(normalizePhone(raw)).toBeNull();
    },
  );

  it("reads a leading 0 as another country when told so", () => {
    expect(normalizePhone("0123 456 789", "60")).toBe("+60123456789");
  });
});
